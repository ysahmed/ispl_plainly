"""Regenerate assets/data/ch07-data.js — the Wage data behind Chapter 7.

    .venv/bin/python tools/ch07_data.py

What is in the file
  CH07_WAGE   the book's Wage data set, in full: the seven survey years,
              every one of the 3,000 rows, wage and log-wage in thousands of
              dollars, and the five categorical predictors as 1-based level
              codes with their labels in `levels`.  Section 7 uses wage ~ age
              for Figures 7.1 to 7.10 and adds year and education for the
              additive models of 7.7, so the whole table ships rather than a
              slice that would need regenerating later.

Nothing here is simulated: unlike Chapter 6, every figure in this chapter is
built from the book's own data.  The file is nevertheless generated rather
than hand-written so the row order, the rounding and the level codes are all
decided in one place and printed in the header below.

Every number in the header comment is executed by this script, never
transcribed.  Sources: ISLP.load_data('Wage') for the data (cross-checked
against _data-src/Wage.csv, the same file the book's package ships), ISLP's
own Poly() transform for the degree-4 table quoted in section 7.8.1, and
pandas.qcut for the cutpoints of section 7.8.2.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
from ISLP import load_data
from ISLP.models import poly, ModelSpec as MS

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "data" / "ch07-data.js"
CSV = ROOT / "_data-src" / "Wage.csv"

W = load_data("Wage")
raw = pd.read_csv(CSV)

# both sources must be the same table, in the same order, before we ship it
for col in ("year", "age", "wage", "logwage"):
    a = W[col].to_numpy(float)
    b = raw[col].to_numpy(float)
    assert np.abs(a - b).max() < 1e-6, f"{col} differs between load_data and the CSV"
assert list(W["education"].astype(str)) == list(raw["education"]), "education labels differ"

n = len(W)
age = W["age"].to_numpy(float)
year = W["year"].to_numpy(int)
wage = W["wage"].to_numpy(float)
logwage = W["logwage"].to_numpy(float)

LEVELS = {
    "education": ["1. < HS Grad", "2. HS Grad", "3. Some College",
                  "4. College Grad", "5. Advanced Degree"],
    "maritl": ["1. Never Married", "2. Married", "3. Widowed",
               "4. Divorced", "5. Separated"],
    "race": ["1. White", "2. Black", "3. Asian", "4. Other"],
    "jobclass": ["1. Industrial", "2. Information"],
    "health": ["1. <=Good", "2. >=Very Good"],
    "health_ins": ["1. Yes", "2. No"],
}


def codes(col):
    """1-based position in the book's own label order."""
    cats = LEVELS[col]
    lut = {label: i + 1 for i, label in enumerate(cats)}
    got = W[col].astype(str)
    assert set(got.unique()) <= set(cats), f"unexpected {col} label"
    return np.array([lut[v] for v in got], dtype=int)


# --------------------------------------------------------------------------
# header checks
checks = []

X4 = np.asarray(MS([poly("age", degree=4)]).fit(W).transform(W))
M4 = sm.OLS(wage, X4).fit()
book = [111.7036, 447.0679, -478.3158, 125.5217, -77.9112]
book_se = [0.729, 39.915, 39.915, 39.915, 39.915]
gap = max(abs(c - b) for c, b in zip(M4.params, book))
gapse = max(abs(s - b) for s, b in zip(M4.bse, book_se))
checks.append(f"n = {n}, years {year.min()}-{year.max()}, age {age.min():.0f}-{age.max():.0f} "
              f"({len(np.unique(age))} distinct), wage {wage.min():.2f}-{wage.max():.2f}")
checks.append(f"observations with wage > 250 = {int((wage > 250).sum())}")
checks.append(f"poly(age, 4) intercept and four orthogonal coefficients vs the book's lab table "
              f"(max |diff|) = {gap:.2e}; standard errors (max |diff|) = {gapse:.2e}")
checks.append(f"degree-4 polynomial RSE = {np.sqrt(M4.mse_resid):.4f}, R2 = {M4.rsquared:.6f}")

cuts = np.quantile(age, [.25, .5, .75])
bins = np.digitize(age, cuts)
checks.append(f"qcut(age, 4) cutpoints = {cuts[0]:.2f}, {cuts[1]:.2f}, {cuts[2]:.2f}; "
              f"mean wage below the first = {wage[bins == 0].mean():.4f}, "
              f"bin sizes = {[int((bins == k).sum()) for k in range(4)]}")
checks.append(f"mean wage by bin = " + ", ".join(f"{wage[bins == k].mean():.1f}" for k in range(4)))

for name in LEVELS:
    c = codes(name)
    bits = [f"{i + 1}={(c == i + 1).sum()}" for i in range(len(LEVELS[name]))]
    checks.append(f"{name}: " + ", ".join(bits))


def arr(vals, nd):
    out = []
    for v in vals:
        f = float(v)
        s = f"{f:.{nd}f}".rstrip("0").rstrip(".")
        out.append(s if s not in ("", "-") else "0")
    return "[" + ",".join(out) + "]"


def intarr(vals):
    return "[" + ",".join(str(int(v)) for v in vals) + "]"


lines = [
    "/* Generated by tools/ch07_data.py — do not edit by hand.",
    "   CH07_WAGE   the book's Wage data, all 3,000 rows: the seven survey years,",
    "               age, wage and log-wage (both in thousands of dollars), and five",
    "               categorical predictors as 1-based level codes.  `levels` gives the",
    "               book's own label for each code, in the book's order.",
    "",
    "   Every figure in Chapter 7 is built from this table — nothing is simulated.",
    "",
    "   Executed checks:",
]
lines += [f"   · {c}" for c in checks]
lines += [
    " */",
    "",
    "window.CH07_LEVELS = {",
]
for name, cats in LEVELS.items():
    lines.append("  " + name + ": [" + ",".join('"' + c + '"' for c in cats) + "],")
lines += [
    "};",
    "",
    "window.CH07_WAGE = {",
    f"  n: {n},",
    "  year: " + intarr(year) + ",",
    "  age: " + intarr(age) + ",",
    "  wage: " + arr(wage, 6) + ",",
    "  logwage: " + arr(logwage, 6) + ",",
    "  education: " + intarr(codes("education")) + ",",
    "  maritl: " + intarr(codes("maritl")) + ",",
    "  race: " + intarr(codes("race")) + ",",
    "  jobclass: " + intarr(codes("jobclass")) + ",",
    "  health: " + intarr(codes("health")) + ",",
    "  health_ins: " + intarr(codes("health_ins")) + ",",
    "};",
]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB)")
for c in checks:
    print("  ·", c)
